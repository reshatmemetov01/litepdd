def price_line(price: int, old_price: int | None) -> str:
    return f"<s>{old_price}</s> {price}₽" if old_price else f"{price}₽"


def legal_line(agreement_url: str, privacy_url: str) -> str:
    docs = []
    if agreement_url:
        docs.append(f'<a href="{agreement_url}">пользовательским соглашением</a>')
    if privacy_url:
        docs.append(f'<a href="{privacy_url}">политикой конфиденциальности</a>')
    if not docs:
        return ""
    return f"\n\n<i>Оплачивая доступ, ты соглашаешься с {' и '.join(docs)}.</i>"


