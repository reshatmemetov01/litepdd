def check_template(key: str, tpl: str) -> tuple[list[str], str | None]:
    """Проверяет новый шаблон. Возвращает (ошибки, пример готового текста)."""
    d = TEXTS[key]
    allowed = {**GLOBAL_PLACEHOLDERS, **(d.placeholders or {})}
    errors: list[str] = []
    try:
        fields = {name for _, name, _, _ in Formatter().parse(tpl) if name is not None}
    except ValueError:
        return ["Непарная фигурная скобка { или }. Если нужна сама скобка — пиши её дважды: {{ или }}."], None
    unknown = sorted(f for f in fields if f not in allowed)
    if unknown:
        errors.append("Неизвестные плейсхолдеры: " + ", ".join("{" + f + "}" for f in unknown)
                      + ". Можно: " + ", ".join("{" + f + "}" for f in allowed))
    missing = [f for f in d.required if f not in fields]
    if missing:
        errors.append("Обязательно оставь в тексте: " + ", ".join("{" + f + "}" for f in missing))
    if errors:
        return errors, None
    try:
        rendered = render(tpl, **sample_values(key))
    except (KeyError, ValueError, IndexError, AttributeError) as e:
        return [f"Текст не форматируется: {e}"], None
    if not rendered.strip():
        return ["Текст пустой."], None
    if len(rendered) > d.limit:
        errors.append(f"Слишком длинный текст: {len(rendered)} символов, максимум {d.limit}.")
    return errors, rendered
