def template(key: str) -> str:
    """Текущий шаблон: из админки, если изменён, иначе стандартный."""
    return runtime.current().texts.get(key) or TEXTS[key].default


def render(tpl: str, **values) -> str:
    return tpl.format(**{"author": "", "bot_name": "", **runtime.current().globals, **values})


def t(key: str, **values) -> str:
    """Готовый текст с подставленными плейсхолдерами."""
    try:
        return render(template(key), **values)
    except (KeyError, ValueError, IndexError, AttributeError):
        # Сломанный шаблон в базе не должен ломать бота — отвечаем стандартным текстом
        return render(TEXTS[key].default, **values)


def followup_text(key: str) -> str:
    return template(f"fu_{key}")


