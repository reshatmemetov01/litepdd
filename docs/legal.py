def to_nodes(text: str) -> list:
    nodes, items = [], []
    for line in text.strip().splitlines():
        line = line.strip()
        if line.startswith("- "):
            items.append({"tag": "li", "children": [line[2:]]})
            continue
        if items:
            nodes.append({"tag": "ul", "children": items})
            items = []
        if not line:
            continue
        if line.startswith("## "):
            nodes.append({"tag": "h4", "children": [line[3:]]})
        else:
            nodes.append({"tag": "p", "children": [line]})
    if items:
        nodes.append({"tag": "ul", "children": items})
    return nodes


def api(method: str, **params) -> dict:
    data = urllib.parse.urlencode({k: json.dumps(v, ensure_ascii=False) if isinstance(v, list) else v
                                   for k, v in params.items()}).encode()
    with urllib.request.urlopen(f"https://api.telegra.ph/{method}", data=data, timeout=30) as resp:
        result = json.load(resp)
    if not result.get("ok"):
        raise RuntimeError(result)
    return result["result"]


def publish(token: str, paths: dict[str, str] | None = None) -> dict[str, str]:
    """Создаёт страницы (или обновляет существующие по paths) и возвращает ссылки."""
    urls = {}
    for key, (title, text) in DOCS.items():
        params = dict(access_token=token, title=title, author_name=SELLER_SHORT, content=to_nodes(text))
        if paths and key in paths:
            page = api(f"editPage/{paths[key]}", **params)
        else:
            page = api("createPage", **params)
        urls[key] = page["url"]
    return urls


